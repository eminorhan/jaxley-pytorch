"""Train or benchmark character-level language models of biophysical networks on
TinyStories (see `models.py` for the networks and `prepare_data.py` for the data).

Training uses `--batch` parallel streams through the training text and truncated
backpropagation through time: every step simulates the next `--chunk` tokens of every
stream (`--ms-per-token` of network time each) starting from the state the previous
step ended in, and backpropagates through that chunk only. Adam; the gradient norm of
every parameter tensor is clipped at 1 (the readout's learning rate is scaled by
1024 / n for larger networks). On GPU, the whole training step (simulation, loss,
backward pass, optimizer step) is captured in a CUDA graph after two eager steps and
replayed.

Modes:
  train     train for `--steps` steps (or `--hours`), evaluate the validation loss
            (bits per character) every `--eval-every` steps; writes `<out>/result.json`.
  bench     a few training steps; reports throughput and memory (`<out>/bench.json`).
  activity  the untrained network driven by text: firing rates (spiking models) or
            mean rates (rate model), to check the input and weight scales.
  sample    text generated by a trained model (`<out>/samples.json`).

Usage:
  python train.py --mode bench --model hh --n 1024 --out <dir>
  python train.py --mode train --model pospischil --n 1024 --hours 4 --out <dir>
  python train.py --mode sample --out <dir of a training run> [--prompt "Once upon a time"]
"""
import argparse
import json
import math
import os
import sys
import time

import numpy as np
import torch
import torch.nn.functional as F

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import jaxley_pytorch as jx
from models import DEFAULTS, MODELS, LanguageModel

DATA = "/nrs/scicompsoft/orhane/probes/jaxley_pytorch/language_modeling/data"


class Streams:
    """`batch` parallel streams through a token file, advanced by `chunk` tokens per
    call; every call returns (batch, chunk + 1) tokens (inputs and next-token targets)."""

    def __init__(self, path: str, batch: int, chunk: int, seed: int = 0, evenly: bool = False):
        self.data = np.memmap(path, dtype=np.uint8, mode="r")
        n = len(self.data)
        if evenly:
            self.pos = np.linspace(0, n - 1, batch, endpoint=False).astype(np.int64)
        else:
            self.pos = np.random.default_rng(seed).integers(0, n, size=batch)
        self.chunk = chunk

    def next(self) -> np.ndarray:
        idx = (self.pos[:, None] + np.arange(self.chunk + 1)) % len(self.data)
        self.pos = (self.pos + self.chunk) % len(self.data)
        return np.asarray(self.data[idx], dtype=np.int64)


def build(args, device, dtype):
    meta = json.load(open(os.path.join(args.data, "meta.json")))
    dt = args.dt if args.dt is not None else DEFAULTS.get(args.model, {}).get("dt", 1.0)
    spt = max(1, int(round(args.ms_per_token / dt)))
    t0 = time.time()
    model = LanguageModel(
        args.model, meta["vocab_size"], args.n, spt, k_in=args.k_in, exc_frac=args.exc_frac, dt=dt,
        input_scale=args.input_scale, w_exc=args.w_exc, w_inh=args.w_inh, seed=args.seed,
        compile=bool(args.compile), inner_checkpoint=args.inner_checkpoint, bptt_tokens=args.bptt_tokens,
    ).to(device=device, dtype=dtype)
    build_s = time.time() - t0
    info = {"model": args.model, "n": args.n, "k_in": args.k_in, "exc_frac": args.exc_frac, "dt_ms": dt,
            "ms_per_token": args.ms_per_token, "steps_per_token": spt, "batch": args.batch, "chunk": args.chunk,
            "dtype": args.dtype, "build_s": build_s, "params": model.num_params(),
            "gpu": torch.cuda.get_device_name(device) if device.type == "cuda" else "cpu",
            "cfg": getattr(model, "cfg", None)}
    if args.model != "gru":
        info["synapses"] = int(len(model.bnet.pre))
        info["compartments"] = int(len(model.bnet.net.nodes))
    print(json.dumps({k: v for k, v in info.items() if k != "params"}), flush=True)
    print("parameters:", info["params"], flush=True)
    return model, meta, info


def evaluate(model, path, batch, chunk, n_chunks, device):
    """Mean cross-entropy (nats per token) over `n_chunks` consecutive chunks of `batch`
    streams spread evenly over the file (the state is carried across chunks)."""
    streams = Streams(path, batch, chunk, evenly=True)
    states = model.initial_state(batch)
    total, count = 0.0, 0
    with torch.no_grad():
        for _ in range(n_chunks):
            tok = torch.as_tensor(streams.next(), device=device)
            logits, states = model(tok[:, :-1], states)
            total += F.cross_entropy(logits.reshape(-1, logits.shape[-1]).float(), tok[:, 1:].reshape(-1), reduction="sum").item()
            count += tok[:, 1:].numel()
    return total / count


def run_training(args, device, dtype, n_steps, time_limit_s=None):
    model, meta, info = build(args, device, dtype)
    vocab = meta["vocab_size"]
    streams = Streams(os.path.join(args.data, "train.bin"), args.batch, args.chunk, seed=args.seed)
    static_tokens = torch.zeros(args.batch, args.chunk + 1, dtype=torch.long, device=device)
    params = [p for p in model.parameters()]
    use_graph = bool(args.graph) and device.type == "cuda"
    side = torch.cuda.Stream() if use_graph else None
    # Everything that touches the parameters before the capture runs on one side stream.
    if side is not None:
        side.wait_stream(torch.cuda.current_stream())
    with torch.cuda.stream(side) if side is not None else torch.no_grad():
        static_states = model.initial_state(args.batch)
    if side is not None:
        torch.cuda.current_stream().wait_stream(side)
    # With Adam, every readout weight moves by ~lr per step, so a logit moves by ~lr * n:
    # the readout's learning rate is scaled by 1024 / n for larger networks.
    readout_scale = args.readout_lr_scale if args.readout_lr_scale is not None else min(1.0, 1024 / args.n)
    readout = [p for name, p in model.named_parameters() if name.startswith("readout")]
    rest = [p for name, p in model.named_parameters() if not name.startswith("readout")]
    opt = torch.optim.Adam([{"params": rest}, {"params": readout, "lr": args.lr * readout_scale}],
                           lr=args.lr, capturable=use_graph)
    info["readout_lr_scale"] = readout_scale

    def iteration():
        opt.zero_grad(set_to_none=False)
        logits, new_states = model(static_tokens[:, :-1], static_states)
        loss = F.cross_entropy(logits.reshape(-1, vocab), static_tokens[:, 1:].reshape(-1))
        loss.backward()
        if args.clip_mode == "global":
            torch.nn.utils.clip_grad_norm_(params, args.clip, foreach=True)
        else:  # Every parameter tensor on its own: exploding network gradients must not
            # scale down the readout's.
            for p in params:
                torch.nn.utils.clip_grad_norm_([p], args.clip)
        opt.step()
        with torch.no_grad():
            for k in static_states:
                static_states[k].copy_(new_states[k])
        return loss.detach()

    losses = torch.zeros(min(n_steps, 10**7), device=device)
    log = {"step": [], "loss": [], "elapsed_s": [], "val_step": [], "val_bpc": []}
    graph, static_loss = None, None
    t_start = time.time()
    t_ready, step_times = None, []
    for step in range(n_steps):
        static_tokens.copy_(torch.as_tensor(streams.next()), non_blocking=False)
        t0 = time.time()
        if graph is not None:
            graph.replay()
        elif use_graph and step < 2:
            side.wait_stream(torch.cuda.current_stream())
            with torch.cuda.stream(side):
                static_loss = iteration()
            torch.cuda.current_stream().wait_stream(side)
        elif use_graph:
            torch.cuda.synchronize()
            graph = torch.cuda.CUDAGraph()
            with torch.cuda.graph(graph):
                static_loss = iteration()
            graph.replay()
        else:
            static_loss = iteration()
        losses[step] = static_loss
        if device.type == "cuda":
            torch.cuda.synchronize()
        step_times.append(time.time() - t0)
        if t_ready is None and step == (2 if use_graph else 1):
            t_ready = time.time() - t_start
            print(f"ready after {t_ready:.1f} s (compilation and graph capture)", flush=True)
        if (step + 1) % args.log_every == 0 or step == n_steps - 1:
            recent = losses[max(0, step + 1 - args.log_every) : step + 1].mean().item()
            dt_step = float(np.median(step_times[3:])) if len(step_times) > 4 else step_times[-1]
            print(f"step {step + 1}: loss {recent:.4f} ({recent / math.log(2):.3f} bpc), {dt_step:.3f} s/step, "
                  f"{args.batch * args.chunk / dt_step:,.0f} tokens/s", flush=True)
            log["step"].append(step + 1)
            log["loss"].append(recent)
            log["elapsed_s"].append(time.time() - t_start)
        out_of_time = time_limit_s is not None and time.time() - t_start > time_limit_s
        last = step == n_steps - 1 or out_of_time
        if args.eval_every and ((step + 1) % args.eval_every == 0 or last):
            val = evaluate(model, os.path.join(args.data, "val.bin"), args.eval_batch, args.chunk, args.eval_chunks, device)
            print(f"step {step + 1}: val loss {val:.4f} ({val / math.log(2):.3f} bpc)", flush=True)
            log["val_step"].append(step + 1)
            log["val_bpc"].append(val / math.log(2))
            log["val_elapsed_s"] = log.get("val_elapsed_s", []) + [time.time() - t_start]
            summary(info, args, step, step_times, t_ready, use_graph, log, device)
            with open(os.path.join(args.out, "result.json"), "w") as f:  # partial, overwritten at the end
                json.dump(dict(info, args=vars(args)), f, indent=1)
        if out_of_time:
            print(f"time limit reached after {step + 1} steps", flush=True)
            break
    summary(info, args, step, step_times, t_ready, use_graph, log, device)
    if args.mode == "train":
        torch.save(model.state_dict(), os.path.join(args.out, "model.pt"))
    return model, info


def summary(info, args, step, step_times, t_ready, use_graph, log, device):
    timed = step_times[3:] if len(step_times) > 4 else step_times
    s_per_step = float(np.median(timed))
    info.update({
        "steps": step + 1, "ready_s": t_ready, "s_per_step": s_per_step,
        "tokens_per_s": args.batch * args.chunk / s_per_step,
        "simulated_ms_per_s": args.batch * args.chunk * args.ms_per_token / s_per_step,
        "ms_per_solver_step": None if args.model == "gru" else 1e3 * s_per_step / (args.chunk * info["steps_per_token"]),
        "peak_memory_gb": torch.cuda.max_memory_allocated(device) / 1e9 if device.type == "cuda" else None,
        "graph": use_graph, "compile": bool(args.compile), "log": log,
    })


def activity(args, device, dtype):
    """Firing rates of the untrained network driven by `--chunk` tokens of text."""
    model, meta, info = build(args, device, dtype)
    tok = torch.as_tensor(Streams(os.path.join(args.data, "train.bin"), args.batch, args.chunk, seed=args.seed).next(), device=device)
    bnet, spt, dt = model.bnet, model.spt, model.cfg["dt"]
    states = model.initial_state(args.batch)
    gs = model.weights().detach()
    currents = model.embed[tok[:, :-1]].detach() * model.input_nA
    spikes, vmean, rates = 0.0, [], []
    with torch.no_grad():
        for k in range(args.chunk):
            stim = currents[:, k, :, None].expand(*currents[:, k].shape, spt)
            v, states = jx.integrate(bnet.net, params=[{f"{bnet.synapse_name}_gS": gs}],
                                     data_stimuli=bnet.input_view.data_stimulate(stim), all_states=states,
                                     return_states=True, delta_t=dt)
            spikes = spikes + ((v[..., 1:] > -20.0) & (v[..., :-1] <= -20.0)).sum(-1).double()
            vmean.append(v[..., 1:].mean(-1))
            if args.model == "rate":
                rates.append(torch.sigmoid((v[..., 1:] + 60.0) * 0.25).mean(-1))
    seconds = args.chunk * args.ms_per_token / 1e3
    hz = (spikes / seconds).cpu().numpy()  # (batch, n)
    e, i = slice(0, bnet.n_exc), slice(bnet.n_exc, bnet.n)
    vm = torch.stack(vmean)
    out = {"mean_v_mV": float(vm[torch.isfinite(vm)].mean()), "nonfinite_frac": float((~torch.isfinite(vm)).double().mean()),
           "rate_hz_exc": float(hz[:, e].mean()), "rate_hz_inh": float(hz[:, i].mean()),
           "silent_frac": float((hz == 0).mean()), "above_100hz_frac": float((hz > 100).mean())}
    if rates:
        r = torch.stack(rates).cpu().numpy()
        out.update({"mean_rate_exc": float(r[..., e].mean()), "mean_rate_inh": float(r[..., i].mean()),
                    "rate_std_over_tokens": float(r.std(0).mean())})
    print(json.dumps(out), flush=True)
    info["activity"] = out
    return info


def sample(args, device, dtype):
    """Generate text from the model trained in `--out` (its `result.json` and `model.pt`)."""
    trained = json.load(open(os.path.join(args.out, "result.json")))["args"]
    for k in ["model", "n", "k_in", "exc_frac", "dt", "ms_per_token", "input_scale", "w_exc", "w_inh", "seed",
              "inner_checkpoint", "dtype", "bptt_tokens"]:
        setattr(args, k, trained.get(k, getattr(args, k)))  # (older runs lack newer options)
    model, meta, _ = build(args, device, dtype)
    model.load_state_dict(torch.load(os.path.join(args.out, "model.pt"), map_location=device))
    chars = meta["chars"]
    stoi = {c: i + 1 for i, c in enumerate(chars)}
    decode = lambda ids: "".join("\n<end of story>\n" if i == 0 else chars[i - 1] for i in ids)
    gen = torch.Generator(device=device).manual_seed(args.seed)
    tok = torch.as_tensor([[stoi[c] for c in args.prompt]] * args.samples, device=device)
    states = model.initial_state(args.samples)
    out = []
    with torch.no_grad():
        logits, states = model(tok, states)
        for _ in range(args.length):
            probs = torch.softmax(logits[:, -1].float() / args.temperature, dim=-1)
            nxt = torch.multinomial(probs, 1, generator=gen)
            out.append(nxt)
            logits, states = model(nxt, states)
    texts = [args.prompt + decode(row.tolist()) for row in torch.cat(out, dim=1).cpu()]
    for i, t in enumerate(texts):
        print(f"--- sample {i} ---\n{t}\n", flush=True)
    return {"prompt": args.prompt, "temperature": args.temperature, "samples": texts}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--mode", choices=["train", "bench", "activity", "sample"], required=True)
    parser.add_argument("--model", choices=MODELS, default=None, help="required except for --mode sample")
    parser.add_argument("--out", required=True)
    parser.add_argument("--data", default=DATA)
    parser.add_argument("--n", type=int, default=1024)
    parser.add_argument("--k-in", type=int, default=100)
    parser.add_argument("--exc-frac", type=float, default=0.8)
    parser.add_argument("--dt", type=float, default=None, help="solver step (ms); default per model")
    parser.add_argument("--ms-per-token", type=float, default=5.0)
    parser.add_argument("--input-scale", type=float, default=None)
    parser.add_argument("--w-exc", type=float, default=None)
    parser.add_argument("--w-inh", type=float, default=None)
    parser.add_argument("--batch", type=int, default=32)
    parser.add_argument("--chunk", type=int, default=32, help="tokens per truncated-BPTT chunk")
    parser.add_argument("--inner-checkpoint", type=int, nargs="*", default=None,
                        help="checkpoint lengths within a token's simulation (product >= steps per token)")
    parser.add_argument("--lr", type=float, default=3e-3)
    parser.add_argument("--clip", type=float, default=1.0)
    parser.add_argument("--clip-mode", choices=["per-param", "global"], default="per-param",
                        help="clip the gradient norm of every parameter tensor, or of all together")
    parser.add_argument("--bptt-tokens", type=int, default=0,
                        help="also truncate the gradient through the network state every k tokens (0: chunk)")
    parser.add_argument("--readout-lr-scale", type=float, default=None,
                        help="readout learning rate / --lr (default min(1, 1024 / n))")
    parser.add_argument("--steps", type=int, default=10)
    parser.add_argument("--hours", type=float, default=None)
    parser.add_argument("--log-every", type=int, default=10)
    parser.add_argument("--eval-every", type=int, default=0)
    parser.add_argument("--eval-batch", type=int, default=64)
    parser.add_argument("--eval-chunks", type=int, default=8)
    parser.add_argument("--dtype", choices=["float32", "float64"], default="float32")
    parser.add_argument("--compile", type=int, default=1)
    parser.add_argument("--graph", type=int, default=1)
    parser.add_argument("--seed", type=int, default=0)
    parser.add_argument("--device", default="cuda")
    parser.add_argument("--prompt", default="Once upon a time")
    parser.add_argument("--length", type=int, default=300)
    parser.add_argument("--samples", type=int, default=3)
    parser.add_argument("--temperature", type=float, default=0.8)
    args = parser.parse_args()
    if args.mode != "sample" and args.model is None:
        parser.error("--model is required")
    os.makedirs(args.out, exist_ok=True)
    dtype = getattr(torch, args.dtype)
    torch.set_default_dtype(dtype)
    device = torch.device(args.device)
    if args.mode == "sample":
        trained = json.load(open(os.path.join(args.out, "result.json")))["args"]
        dtype = getattr(torch, trained["dtype"])
        torch.set_default_dtype(dtype)
        info = sample(args, device, dtype)
        name = "samples.json"
    elif args.mode == "activity":
        info = activity(args, device, dtype)
        name = "activity.json"
    else:
        hours = args.hours if args.mode == "train" else None
        n_steps = args.steps if hours is None else 10**9
        _, info = run_training(args, device, dtype, n_steps, None if hours is None else hours * 3600)
        name = "result.json" if args.mode == "train" else "bench.json"
        print(f"{info['s_per_step']:.3f} s/step, {info['tokens_per_s']:,.0f} tokens/s, "
              f"peak memory {info['peak_memory_gb']} GB", flush=True)
    info["args"] = vars(args)
    with open(os.path.join(args.out, name), "w") as f:
        json.dump(info, f, indent=1)


if __name__ == "__main__":
    main()
